// 主題集 03 への感想（「シンプルな、スケールをそのまま移動するような旋律で、コードと綺麗に調和するもの」
// 「単調」「しばらく同じ調でメロディで変化を」「最後が転調にひっぱられている」）を受けた6案。
// - 旋律は順次進行（音階）を骨格にし、強拍には和音の音（または長7度・9度）を置く。
// - 4小節ごとにリズムの型を変え、山場の最高音は1か所に絞る。
// - 平行移動や借用和音は1–2小節の色づけにとどめ、最後は主調の終止で頭へ戻る。

type Voicing = readonly string[]

// 4/4: 8分の分散和音。前半と後半で別の和音を指定できる。
const flow44 = (x: Voicing, y: Voicing = x) =>
  `${x[0]}:.5 ${x[1]} ${x[2]} ${x[1]} ${y[0]} ${y[1]} ${y[2]} ${y[1]}`

// 3/4: 1拍目を低音に任せ、2・3拍目に和音を置くワルツ
const waltz = (x: string, y: string = x) => `r:1 ${x}:1 ${y}:1`

// 6/8: 拍頭を休み、8分2つで和音を揺らす
const sway68 = (x: string, y: string = x) => `r:.5 ${x}:.5 ${x}:.5 r:.5 ${y}:.5 ${y}:.5`

// 12/8: 8分で上下する波
const wave128 = (x: Voicing, y: Voicing = x) =>
  `${x[0]}:.5 ${x[1]} ${x[2]} ${x[3]} ${x[2]} ${x[1]} ${y[0]} ${y[1]} ${y[2]} ${y[3]} ${y[2]} ${y[1]}`

// 4/4: 3音を駆け上がって保つ鐘の音型
const chime44 = (x: Voicing) => `${x[0]}:.5 ${x[1]} ${x[2]} ${x[3]}:1.5 ${x[2]}:.5 ${x[1]}:.5`
const chimeSplit44 = (x: Voicing, y: Voicing) => `${x[0]}:.5 ${x[1]}:.5 ${x[2]}:1 ${y[0]}:.5 ${y[1]}:.5 ${y[2]}:1`

