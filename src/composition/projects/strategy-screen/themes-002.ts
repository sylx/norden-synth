interface ThemeDraft {
  id: string
  title: string
  description: string
  tempo: number
  meter: readonly [number, number]
  harmonyGate: number
  bassGate: number
  chords: string[]
  melody: string[]
  counter: string[]
  harmony: string[]
  bass: string[]
  phrases: CompositionStudy['phrases']
  moments: CompositionStudy['moments']
}

function buildTheme(draft: ThemeDraft): CompositionStudy {
  const song: Song = {
    id: draft.id,
    title: draft.title,
    description: draft.description,
    tempo: draft.tempo,
    timeSignature: draft.meter,
    intro: [],
    loop: ['theme'],
    parts: [
      { id: 'melody', label: '主題', instrument: 'yamaha-grand-piano', volume: 0.66, pan: 0.04, velocity: 82, gate: 0.96 },
      { id: 'counter', label: '内声・対旋律', instrument: 'yamaha-grand-piano', volume: 0.44, pan: -0.14, velocity: 60, gate: 1.08 },
      { id: 'harmony', label: '和声・伴奏', instrument: 'yamaha-grand-piano', volume: 0.38, pan: 0.16, velocity: 56, gate: draft.harmonyGate },
      { id: 'bass', label: '低音', instrument: 'yamaha-grand-piano', volume: 0.5, pan: -0.08, velocity: 68, gate: draft.bassGate },
    ],
    sections: [
      {
        id: 'theme',
        label: draft.title,
        chords: draft.chords,
        parts: {
          melody: draft.melody,
          counter: draft.counter,
          harmony: draft.harmony,
          bass: draft.bass,
        },
      },
    ],
  }
  return {
    song,
    melodyPart: 'melody',
    hypothesis: draft.description,
    phrases: draft.phrases,
    moments: draft.moments,
  }
}

